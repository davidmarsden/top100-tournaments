-- Season close: archive readiness checks, a durable archive snapshot with
-- honours, and an auditable end-of-season prize draw.
--
-- * tournament_archive_checks(id)  — what still blocks (or should be looked at
--   before) archiving a tournament.
-- * archive_tournament(id, force)  — records Winner/Runner-up honours for every
--   knockout bracket, stores a full JSON snapshot, and marks the tournament
--   archived. Safe to run again: honours are replaced and a new snapshot added.
-- * prize_draw_pool(id)            — every manager in the tournament with their
--   fair-play status (any forfeit that affects the prize draw excludes them).
-- * run_prize_draw(...)            — draws winners on the server with a fresh
--   random seed. Each candidate's rank is sha256(seed || ':' || key), lowest
--   first, so anyone can re-check a published draw from its seed and list.
-- * public_tournament_honours()    — archived honours for the archive site.

-- ---------------------------------------------------------------------------
-- Archive snapshots
-- ---------------------------------------------------------------------------
create table if not exists public.tournament_archive_snapshots (
  id bigint generated by default as identity primary key,
  tournament_id bigint not null references public.tournaments(id) on delete cascade,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid(),
  honours jsonb not null default '[]'::jsonb,
  checks jsonb not null default '[]'::jsonb,
  snapshot jsonb not null
);

comment on table public.tournament_archive_snapshots is
  'Full JSON copy of a tournament (entries, groups, matches, forfeits, honours) taken each time it is archived. Written only by archive_tournament().';

create index if not exists tournament_archive_snapshots_tournament_idx
  on public.tournament_archive_snapshots (tournament_id, created_at desc);

alter table public.tournament_archive_snapshots enable row level security;

drop policy if exists "Staff read archive snapshots" on public.tournament_archive_snapshots;
create policy "Staff read archive snapshots" on public.tournament_archive_snapshots
  for select to authenticated
  using ((select public.can_assist_tournament(tournament_id)));

revoke all on public.tournament_archive_snapshots from anon;
grant select on public.tournament_archive_snapshots to authenticated;

-- ---------------------------------------------------------------------------
-- Readiness checks
-- ---------------------------------------------------------------------------
create or replace function public.tournament_archive_checks(p_tournament_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  result jsonb := '[]'::jsonb;
  item record;
begin
  if not (public.can_assist_tournament(p_tournament_id) or public.is_admin()) then
    raise exception 'Tournament staff access required';
  end if;

  -- Fixtures without a result.
  for item in
    select m.id, m.stage, m.bracket, m.round, m.leg
    from public.matches m
    where m.tournament_id = p_tournament_id
      and coalesce(m.status, 'scheduled') not in ('played', 'forfeit', 'voided')
    order by m.fixture_date nulls last, m.id
  loop
    result := result || jsonb_build_object(
      'level', 'error', 'code', 'unplayed_fixture', 'match_id', item.id,
      'message', format('%s %s%s has no result yet', coalesce(item.bracket, item.stage), item.round,
        case when item.leg > 1 then ' leg ' || item.leg else '' end));
  end loop;

  -- Manager-submitted results still under review.
  for item in
    select s.match_id, s.status, m.round, m.bracket
    from public.manager_result_submissions s
    join public.matches m on m.id = s.match_id
    where m.tournament_id = p_tournament_id
      and s.status in ('pending_confirmation', 'disputed', 'pending_admin_check', 'opponent_confirmed', 'appealed')
  loop
    result := result || jsonb_build_object(
      'level', 'error', 'code', 'result_under_review', 'match_id', item.match_id,
      'message', format('%s %s result is still %s', coalesce(item.bracket, ''), item.round, replace(item.status, '_', ' ')));
  end loop;

  -- Every knockout tie's deciding leg needs a winner (except double forfeits and byes).
  for item in
    with ko as (
      select m.*,
             least(m.home_entry_id, m.away_entry_id) as side_a,
             greatest(m.home_entry_id, m.away_entry_id) as side_b
      from public.matches m
      where m.tournament_id = p_tournament_id and m.stage = 'knockout'
        and m.status in ('played', 'forfeit')
        and m.home_entry_id is not null and m.away_entry_id is not null
    ), deciding as (
      select distinct on (coalesce(bracket, 'Cup'), round, side_a, side_b) *
      from ko
      order by coalesce(bracket, 'Cup'), round, side_a, side_b, leg desc
    )
    select id, bracket, round, leg from deciding
    where winner_entry_id is null and coalesce(decided_by, '') <> 'double_forfeit' and side_a <> side_b
  loop
    result := result || jsonb_build_object(
      'level', 'error', 'code', 'tie_without_winner', 'match_id', item.id,
      'message', format('%s %s tie has no recorded winner on its deciding leg', coalesce(item.bracket, 'Cup'), item.round));
  end loop;

  -- Each knockout bracket needs a decided Final.
  for item in
    select b.bracket,
           (select f.winner_entry_id from public.matches f
             where f.tournament_id = p_tournament_id and f.stage = 'knockout'
               and coalesce(f.bracket, 'Cup') = b.bracket and f.round = 'Final'
               and f.status in ('played', 'forfeit')
             order by f.leg desc limit 1) as winner
    from (select distinct coalesce(bracket, 'Cup') as bracket from public.matches
          where tournament_id = p_tournament_id and stage = 'knockout') b
  loop
    if item.winner is null then
      result := result || jsonb_build_object(
        'level', 'error', 'code', 'final_undecided',
        'message', format('%s Final has no winner yet', item.bracket));
    end if;
  end loop;

  if not exists (select 1 from public.matches where tournament_id = p_tournament_id and stage = 'knockout') then
    result := result || jsonb_build_object('level', 'error', 'code', 'no_knockout', 'message', 'No knockout stage has been played');
  end if;

  -- Forfeit results without a discipline record (warning only).
  for item in
    select m.id, m.round, m.bracket from public.matches m
    where m.tournament_id = p_tournament_id and m.status = 'forfeit'
      and not exists (select 1 from public.forfeits f where f.match_id = m.id)
  loop
    result := result || jsonb_build_object(
      'level', 'warning', 'code', 'forfeit_without_record', 'match_id', item.id,
      'message', format('%s %s is a forfeit with no manager discipline record', coalesce(item.bracket, ''), item.round));
  end loop;

  -- Forfeit records with no responsible manager (warning only).
  for item in
    select f.id, m.round from public.forfeits f join public.matches m on m.id = f.match_id
    where m.tournament_id = p_tournament_id and f.manager_id is null
  loop
    result := result || jsonb_build_object(
      'level', 'warning', 'code', 'forfeit_without_manager',
      'message', format('A %s forfeit has no responsible manager, so it cannot affect the prize draw', item.round));
  end loop;

  return result;
end;
$$;

revoke all on function public.tournament_archive_checks(bigint) from public, anon;
grant execute on function public.tournament_archive_checks(bigint) to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- Archive
-- ---------------------------------------------------------------------------
create or replace function public.archive_tournament(p_tournament_id bigint, p_force boolean default false)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  checks jsonb;
  error_count int;
  tournament_row public.tournaments%rowtype;
  label_prefix text;
  final_row record;
  honours_json jsonb;
  snapshot_json jsonb;
  snapshot_id bigint;
begin
  if not public.can_manage_tournament(p_tournament_id) then
    raise exception 'Tournament organiser access required';
  end if;

  select * into tournament_row from public.tournaments where id = p_tournament_id for update;
  if not found then raise exception 'Tournament % not found', p_tournament_id; end if;

  checks := public.tournament_archive_checks(p_tournament_id);
  select count(*) into error_count from jsonb_array_elements(checks) c where c->>'level' = 'error';
  if error_count > 0 and not (p_force and public.is_admin()) then
    raise exception 'Tournament is not ready to archive: % blocking issue(s). Run the archive checks for details.', error_count;
  end if;

  label_prefix := case when tournament_row.name ilike '%youth%' then 'Youth ' else '' end;

  -- Replace honours with Winner / Runner-up for every knockout bracket.
  delete from public.honours where tournament_id = p_tournament_id;
  for final_row in
    select distinct on (coalesce(m.bracket, 'Cup'))
           coalesce(m.bracket, 'Cup') as bracket, m.winner_entry_id,
           case when m.winner_entry_id = m.home_entry_id then m.away_entry_id else m.home_entry_id end as runner_up
    from public.matches m
    where m.tournament_id = p_tournament_id and m.stage = 'knockout' and m.round = 'Final'
      and m.status in ('played', 'forfeit') and m.winner_entry_id is not null
    order by coalesce(m.bracket, 'Cup'), m.leg desc
  loop
    insert into public.honours (tournament_id, entry_id, honour, position)
    values (p_tournament_id, final_row.winner_entry_id, label_prefix || final_row.bracket || ' Winner', 1);
    if final_row.runner_up is not null and final_row.runner_up <> final_row.winner_entry_id then
      insert into public.honours (tournament_id, entry_id, honour, position)
      values (p_tournament_id, final_row.runner_up, label_prefix || final_row.bracket || ' Runner-up', 2);
    end if;
  end loop;

  select coalesce(jsonb_agg(jsonb_build_object(
           'honour', h.honour, 'position', h.position, 'entry_id', h.entry_id,
           'team_name', t.name, 'manager_name', coalesce(mg.display_name, mg.name))
           order by h.honour like '%Shield%', h.position), '[]'::jsonb)
    into honours_json
  from public.honours h
  left join public.tournament_entries e on e.id = h.entry_id
  left join public.teams t on t.id = e.team_id
  left join public.managers mg on mg.id = e.manager_id
  where h.tournament_id = p_tournament_id;

  snapshot_json := jsonb_build_object(
    'schema', 1,
    'taken_at', now(),
    'tournament', to_jsonb(tournament_row),
    'honours', honours_json,
    'groups', coalesce((select jsonb_agg(to_jsonb(g) order by g.group_order) from public.groups g where g.tournament_id = p_tournament_id), '[]'::jsonb),
    'entries', coalesce((select jsonb_agg(to_jsonb(e) || jsonb_build_object('team_name', t.name, 'manager_name', coalesce(mg.display_name, mg.name)) order by e.id)
                from public.tournament_entries e
                left join public.teams t on t.id = e.team_id
                left join public.managers mg on mg.id = e.manager_id
                where e.tournament_id = p_tournament_id), '[]'::jsonb),
    'matches', coalesce((select jsonb_agg(to_jsonb(m) order by m.stage desc, m.bracket, m.fixture_date, m.match_order, m.id) from public.matches m where m.tournament_id = p_tournament_id), '[]'::jsonb),
    'forfeits', coalesce((select jsonb_agg(to_jsonb(f) || jsonb_build_object('manager_name', coalesce(mg.display_name, mg.name)) order by f.id)
                from public.forfeits f join public.matches m on m.id = f.match_id
                left join public.managers mg on mg.id = f.manager_id
                where m.tournament_id = p_tournament_id), '[]'::jsonb),
    'round_dates', coalesce((select jsonb_agg(to_jsonb(r) order by r.id) from public.tournament_round_dates r where r.tournament_id = p_tournament_id), '[]'::jsonb)
  );

  insert into public.tournament_archive_snapshots (tournament_id, honours, checks, snapshot)
  values (p_tournament_id, honours_json, checks, snapshot_json)
  returning id into snapshot_id;

  update public.tournaments
     set status = 'archived',
         archived_at = coalesce(archived_at, now()),
         archive_quality = 'complete',
         is_public = true
   where id = p_tournament_id;

  return jsonb_build_object('snapshot_id', snapshot_id, 'honours', honours_json, 'checks', checks);
end;
$$;

revoke all on function public.archive_tournament(bigint, boolean) from public, anon;
grant execute on function public.archive_tournament(bigint, boolean) to authenticated, service_role;

-- Archived honours for the archive site and public pages.
create or replace function public.public_tournament_honours()
returns table (
  tournament_id bigint, tournament_name text, season_number int,
  honour text, position int, team_name text, manager_name text
)
language sql
stable
security definer
set search_path = ''
as $$
  select t.id, t.name, t.season_number, h.honour, h.position, tm.name, coalesce(mg.display_name, mg.name)
  from public.honours h
  join public.tournaments t on t.id = h.tournament_id
  left join public.tournament_entries e on e.id = h.entry_id
  left join public.teams tm on tm.id = e.team_id
  left join public.managers mg on mg.id = e.manager_id
  where t.is_public and t.status in ('completed', 'archived')
  order by t.season_number desc nulls last, h.honour, h.position;
$$;

revoke all on function public.public_tournament_honours() from public;
grant execute on function public.public_tournament_honours() to anon, authenticated, service_role;

-- ---------------------------------------------------------------------------
-- Prize draw
-- ---------------------------------------------------------------------------
create or replace function public.prize_draw_pool(p_tournament_id bigint)
returns table (
  manager_id bigint, manager_name text, team_name text, entry_id bigint,
  is_current_manager boolean, forfeit_count int, draw_forfeit_count int,
  entry_flag boolean, eligible boolean, reason text
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not (public.tournament_is_public(p_tournament_id) or public.can_assist_tournament(p_tournament_id)) then
    raise exception 'Tournament not found';
  end if;

  return query
  with current_managers as (
    select e.manager_id, e.id as entry_id, e.team_id, e.prize_draw_eligible
    from public.tournament_entries e
    where e.tournament_id = p_tournament_id and e.manager_id is not null
  ), forfeit_rows as (
    select f.manager_id, count(*)::int as total,
           count(*) filter (where f.affects_prize_draw is distinct from false)::int as draw_total
    from public.forfeits f join public.matches m on m.id = f.match_id
    where m.tournament_id = p_tournament_id and f.manager_id is not null
    group by f.manager_id
  ), people as (
    select manager_id from current_managers union select manager_id from forfeit_rows
  )
  select p.manager_id,
         coalesce(mg.display_name, mg.name, 'Unknown manager'),
         t.name,
         cm.entry_id,
         cm.entry_id is not null,
         coalesce(fr.total, 0),
         coalesce(fr.draw_total, 0),
         cm.prize_draw_eligible,
         (cm.entry_id is not null and coalesce(fr.draw_total, 0) = 0 and cm.prize_draw_eligible is distinct from false),
         case
           when coalesce(fr.draw_total, 0) > 0 then format('%s forfeit%s', fr.draw_total, case when fr.draw_total = 1 then '' else 's' end)
           when cm.prize_draw_eligible = false then 'Excluded by organiser'
           when cm.entry_id is null then 'No longer managing an entrant'
           else null
         end
  from people p
  left join current_managers cm on cm.manager_id = p.manager_id
  left join forfeit_rows fr on fr.manager_id = p.manager_id
  left join public.managers mg on mg.id = p.manager_id
  left join public.teams t on t.id = cm.team_id
  order by 9 desc, 2;
end;
$$;

revoke all on function public.prize_draw_pool(bigint) from public;
grant execute on function public.prize_draw_pool(bigint) to anon, authenticated, service_role;

create table if not exists public.prize_draws (
  id bigint generated by default as identity primary key,
  tournament_id bigint references public.tournaments(id) on delete set null,
  season_number int,
  title text not null,
  prize text,
  winners_count int not null check (winners_count between 1 and 50),
  candidates jsonb not null,
  excluded jsonb not null default '[]'::jsonb,
  seed text not null,
  winners jsonb not null,
  drawn_by uuid default auth.uid(),
  drawn_at timestamptz not null default now(),
  published boolean not null default false,
  voided boolean not null default false,
  void_reason text
);

comment on table public.prize_draws is
  'Every prize draw that was run, including re-draws. Rank = sha256(seed || '':'' || candidate key), lowest first. Written only by run_prize_draw(), publish_prize_draw() and void_prize_draw().';

create index if not exists prize_draws_tournament_idx on public.prize_draws (tournament_id, drawn_at desc);

alter table public.prize_draws enable row level security;

drop policy if exists "Anyone reads published prize draws" on public.prize_draws;
create policy "Anyone reads published prize draws" on public.prize_draws
  for select to anon, authenticated
  using (published and not voided);

drop policy if exists "Staff read prize draws" on public.prize_draws;
create policy "Staff read prize draws" on public.prize_draws
  for select to authenticated
  using ((select public.is_admin()) or (tournament_id is not null and (select public.can_assist_tournament(tournament_id))));

revoke all on public.prize_draws from anon, authenticated;
grant select on public.prize_draws to anon, authenticated;

create or replace function public.run_prize_draw(
  p_tournament_id bigint,
  p_title text,
  p_winners_count int,
  p_candidates jsonb,
  p_excluded jsonb default '[]'::jsonb,
  p_prize text default null
)
returns public.prize_draws
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  candidate_count int;
  distinct_count int;
  draw_seed text;
  ranked jsonb;
  row_out public.prize_draws;
begin
  if p_tournament_id is null then
    if not public.is_admin() then raise exception 'Admin access required'; end if;
  elsif not public.can_manage_tournament(p_tournament_id) then
    raise exception 'Tournament organiser access required';
  end if;

  if jsonb_typeof(p_candidates) <> 'array' then raise exception 'Candidates must be a list'; end if;
  select count(*), count(distinct trim(c->>'key'))
    into candidate_count, distinct_count
  from jsonb_array_elements(p_candidates) c;
  if exists (select 1 from jsonb_array_elements(p_candidates) c where coalesce(trim(c->>'key'), '') = '' or coalesce(trim(c->>'name'), '') = '') then
    raise exception 'Every candidate needs a key and a name';
  end if;
  if distinct_count <> candidate_count then raise exception 'Candidate list contains duplicates'; end if;
  if p_winners_count < 1 or p_winners_count > candidate_count then
    raise exception 'Cannot draw % winner(s) from % candidate(s)', p_winners_count, candidate_count;
  end if;
  if coalesce(trim(p_title), '') = '' then raise exception 'Give the draw a title'; end if;

  draw_seed := encode(extensions.gen_random_bytes(32), 'hex');

  select jsonb_agg(c || jsonb_build_object('rank', rn, 'hash', h) order by rn)
    into ranked
  from (
    select c, h, row_number() over (order by h) as rn
    from (
      select c, encode(sha256(convert_to(draw_seed || ':' || trim(c->>'key'), 'UTF8')), 'hex') as h
      from jsonb_array_elements(p_candidates) c
    ) hashed
  ) ordered
  where rn <= p_winners_count;

  insert into public.prize_draws (tournament_id, season_number, title, prize, winners_count, candidates, excluded, seed, winners)
  values (
    p_tournament_id,
    (select season_number from public.tournaments where id = p_tournament_id),
    trim(p_title), nullif(trim(coalesce(p_prize, '')), ''), p_winners_count,
    p_candidates, coalesce(p_excluded, '[]'::jsonb), draw_seed, ranked)
  returning * into row_out;

  return row_out;
end;
$$;

revoke all on function public.run_prize_draw(bigint, text, int, jsonb, jsonb, text) from public, anon;
grant execute on function public.run_prize_draw(bigint, text, int, jsonb, jsonb, text) to authenticated, service_role;

create or replace function public.publish_prize_draw(p_draw_id bigint, p_published boolean)
returns public.prize_draws
language plpgsql
security definer
set search_path = ''
as $$
declare
  draw_row public.prize_draws;
begin
  select * into draw_row from public.prize_draws where id = p_draw_id for update;
  if not found then raise exception 'Prize draw not found'; end if;
  if not (public.is_admin() or (draw_row.tournament_id is not null and public.can_manage_tournament(draw_row.tournament_id))) then
    raise exception 'Tournament organiser access required';
  end if;
  if draw_row.voided and p_published then raise exception 'A voided draw cannot be published'; end if;

  -- Only one published draw per tournament + title.
  if p_published then
    update public.prize_draws set published = false
     where id <> p_draw_id and published
       and tournament_id is not distinct from draw_row.tournament_id
       and title = draw_row.title;
  end if;

  update public.prize_draws set published = p_published where id = p_draw_id returning * into draw_row;
  return draw_row;
end;
$$;

revoke all on function public.publish_prize_draw(bigint, boolean) from public, anon;
grant execute on function public.publish_prize_draw(bigint, boolean) to authenticated, service_role;

create or replace function public.void_prize_draw(p_draw_id bigint, p_reason text)
returns public.prize_draws
language plpgsql
security definer
set search_path = ''
as $$
declare
  draw_row public.prize_draws;
begin
  select * into draw_row from public.prize_draws where id = p_draw_id for update;
  if not found then raise exception 'Prize draw not found'; end if;
  if not (public.is_admin() or (draw_row.tournament_id is not null and public.can_manage_tournament(draw_row.tournament_id))) then
    raise exception 'Tournament organiser access required';
  end if;
  if coalesce(trim(p_reason), '') = '' then raise exception 'Give a reason for voiding the draw'; end if;

  update public.prize_draws
     set voided = true, published = false, void_reason = trim(p_reason)
   where id = p_draw_id
  returning * into draw_row;
  return draw_row;
end;
$$;

revoke all on function public.void_prize_draw(bigint, text) from public, anon;
grant execute on function public.void_prize_draw(bigint, text) to authenticated, service_role;
