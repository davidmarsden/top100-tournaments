-- Candidate baseline v0: objects that exist in production but are created by NO SQL file
-- anywhere in the repository's full git history (dashboard-created, pre-July 2026).
-- Source: read-only catalog queries against production on 2026-10-11.
-- Columns, constraints and policies that later repo SQL adds are deliberately excluded
-- so the historical scripts can add them themselves.

create table public.seasons (
  id bigint generated by default as identity primary key,
  code text not null unique,
  number integer,
  start_date date,
  end_date date
);

create table public.competitions (
  id bigint generated by default as identity primary key,
  name text not null unique,
  competition_type text,
  description text
);

create table public.tournament_formats (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  has_group_stage boolean default true,
  has_knockout_stage boolean default true,
  has_secondary_bracket boolean default false,
  group_size integer,
  legs_group_stage integer default 1,
  legs_knockout_stage integer default 1,
  notes text
);

create table public.teams (
  id bigint generated by default as identity primary key,
  name text not null unique,
  short_name text,
  country text,
  active boolean default true
);

create table public.managers (
  id bigint generated by default as identity primary key,
  name text not null,
  canonical_name text,
  active boolean default true,
  display_name text,
  discord_name text,
  joined_season_id bigint references public.seasons(id),
  retired_season_id bigint references public.seasons(id)
);

create table public.team_aliases (
  id bigint generated by default as identity primary key,
  team_id bigint references public.teams(id) on delete cascade,
  alias text not null,
  source text,
  unique (team_id, alias)
);

create table public.manager_clubs (
  id bigint generated by default as identity primary key,
  manager_id bigint references public.managers(id) on delete cascade,
  team_id bigint references public.teams(id) on delete cascade,
  from_season_id bigint references public.seasons(id),
  to_season_id bigint references public.seasons(id),
  current_club boolean default false,
  appointment_type text,
  notes text
);

create table public.tournaments (
  id bigint generated by default as identity primary key,
  season_id bigint references public.seasons(id),
  competition_id bigint references public.competitions(id),
  name text not null,
  status text default 'draft',
  format text,
  source text default 'manual',
  source_id text,
  created_at timestamptz default now(),
  format_id bigint references public.tournament_formats(id),
  max_entries integer,
  actual_entries integer,
  group_count integer,
  teams_per_group integer,
  knockout_teams integer,
  secondary_bracket_name text,
  rules_notes text
);

create table public.tournament_stages (
  id bigint generated by default as identity primary key,
  tournament_id bigint references public.tournaments(id) on delete cascade,
  name text not null,
  stage_type text not null,
  stage_order integer not null,
  bracket_name text,
  entrants_from text,
  notes text,
  unique (tournament_id, name)
);

create table public.tournament_rounds (
  id bigint generated by default as identity primary key,
  tournament_id bigint references public.tournaments(id) on delete cascade,
  stage_id bigint references public.tournament_stages(id) on delete cascade,
  name text not null,
  round_order integer not null,
  round_type text not null,
  legs integer default 1,
  scheduled_at timestamptz,
  notes text,
  unique (stage_id, name)
);

create table public.groups (
  id bigint generated by default as identity primary key,
  tournament_id bigint references public.tournaments(id) on delete cascade,
  code text not null,
  name text,
