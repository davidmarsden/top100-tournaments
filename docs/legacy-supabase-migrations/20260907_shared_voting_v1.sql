  public.is_admin() or exists (
    select 1 from public.manager_portal_accounts a
    join public.voting_electorate e on e.manager_id = a.manager_id
    where a.auth_user_id = auth.uid() and a.active = true and e.event_id = voting_events.id
  )
);
create policy "Eligible managers can read voting questions" on public.voting_questions for select to authenticated using (
  public.is_admin() or exists (
    select 1 from public.manager_portal_accounts a
    join public.voting_electorate e on e.manager_id = a.manager_id
    where a.auth_user_id = auth.uid() and a.active = true and e.event_id = voting_questions.event_id
  )
);
create policy "Eligible managers can read voting options" on public.voting_options for select to authenticated using (
  public.is_admin() or exists (
    select 1 from public.voting_questions q
    join public.manager_portal_accounts a on a.auth_user_id = auth.uid() and a.active = true
    join public.voting_electorate e on e.manager_id = a.manager_id and e.event_id = q.event_id
    where q.id = voting_options.question_id
  )
);
create policy "Managers can read their electorate record" on public.voting_electorate for select to authenticated using (
  public.is_admin() or exists (
    select 1 from public.manager_portal_accounts a
    where a.auth_user_id = auth.uid() and a.active = true and a.manager_id = voting_electorate.manager_id
  )
);
create policy "Managers can read their own ballots" on public.voting_ballots for select to authenticated using (
  public.is_admin() or exists (
    select 1 from public.manager_portal_accounts a
    where a.auth_user_id = auth.uid() and a.active = true and a.manager_id = voting_ballots.manager_id
  )
);
create policy "Managers can read their own responses" on public.voting_responses for select to authenticated using (
  public.is_admin() or exists (
    select 1 from public.voting_ballots b
    join public.manager_portal_accounts a on a.manager_id = b.manager_id
    where b.id = voting_responses.ballot_id and a.auth_user_id = auth.uid() and a.active = true
  )
);

