-- Shared manager-authenticated voting foundation (V1)
-- Reuses Supabase Auth + manager_portal_accounts as the canonical voter identity.

create table if not exists public.voting_events (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  description text,
  event_type text not null default 'poll' check (event_type in ('poll', 'awards', 'test')),
  status text not null default 'draft' check (status in ('draft', 'open', 'closed', 'cancelled')),
  opens_at timestamptz,
  closes_at timestamptz,
  results_visibility text not null default 'after_close' check (results_visibility in ('hidden', 'after_close', 'live')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint voting_events_close_after_open check (closes_at is null or opens_at is null or closes_at > opens_at)
);

create table if not exists public.voting_questions (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.voting_events(id) on delete cascade,
  title text not null,
  description text,
  question_type text not null check (question_type in ('yes_no', 'single_choice')),
  required boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.voting_options (
  id bigint generated by default as identity primary key,
  question_id bigint not null references public.voting_questions(id) on delete cascade,
  label text not null,
  value text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique(question_id, label)
);

create table if not exists public.voting_electorate (
  event_id bigint not null references public.voting_events(id) on delete cascade,
  manager_id bigint not null references public.managers(id) on delete restrict,
  manager_account_id bigint references public.manager_portal_accounts(id) on delete set null,
  manager_name text not null,
  included_at timestamptz not null default now(),
  primary key(event_id, manager_id)
);

create table if not exists public.voting_ballots (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.voting_events(id) on delete cascade,
  manager_id bigint not null references public.managers(id) on delete restrict,
  submitted_by uuid not null references auth.users(id) on delete restrict,
  submitted_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(event_id, manager_id)
);

create table if not exists public.voting_responses (
  ballot_id bigint not null references public.voting_ballots(id) on delete cascade,
  question_id bigint not null references public.voting_questions(id) on delete cascade,
  option_id bigint not null references public.voting_options(id) on delete restrict,
  created_at timestamptz not null default now(),
  primary key(ballot_id, question_id)
);

create table if not exists public.voting_audit_log (
  id bigint generated by default as identity primary key,
  event_id bigint references public.voting_events(id) on delete cascade,
  ballot_id bigint references public.voting_ballots(id) on delete set null,
  actor_user_id uuid references auth.users(id) on delete set null,
  manager_id bigint references public.managers(id) on delete set null,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists voting_questions_event_idx on public.voting_questions(event_id, sort_order, id);
create index if not exists voting_options_question_idx on public.voting_options(question_id, sort_order, id);
create index if not exists voting_electorate_account_idx on public.voting_electorate(manager_account_id);
create index if not exists voting_responses_question_idx on public.voting_responses(question_id, option_id);
create index if not exists voting_audit_event_idx on public.voting_audit_log(event_id, created_at);

