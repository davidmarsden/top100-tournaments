create or replace function public.open_voting_event(target_event_id bigint)
returns integer language plpgsql security definer set search_path = public as $$
declare
  electorate_count integer;
  v_event public.voting_events%rowtype;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  select * into v_event from public.voting_events where id = target_event_id for update;
  if not found then raise exception 'Voting event not found'; end if;
  if v_event.status <> 'draft' then raise exception 'Only draft voting events can be opened'; end if;
  if v_event.closes_at is null or v_event.closes_at <= now() then raise exception 'Set a future closing time before opening the vote'; end if;

  delete from public.voting_electorate where event_id = target_event_id;
  insert into public.voting_electorate(event_id, manager_id, manager_account_id, manager_name)
  select target_event_id, a.manager_id, a.id, coalesce(nullif(m.display_name, ''), m.name)
  from public.manager_portal_accounts a join public.managers m on m.id = a.manager_id
  where a.active = true;
  get diagnostics electorate_count = row_count;
  if electorate_count = 0 then raise exception 'No active manager accounts are available for the electorate'; end if;

  update public.voting_events set status = 'open', opens_at = coalesce(opens_at, now()), updated_at = now() where id = target_event_id;
  insert into public.voting_audit_log(event_id, actor_user_id, action, details)
  values (target_event_id, auth.uid(), 'event_opened', jsonb_build_object('electorate_count', electorate_count));
  return electorate_count;
end $$;
grant execute on function public.open_voting_event(bigint) to authenticated;

create or replace function public.close_voting_event(target_event_id bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  update public.voting_events set status = 'closed', closes_at = least(coalesce(closes_at, now()), now()), updated_at = now()
  where id = target_event_id and status = 'open';
  if not found then raise exception 'Open voting event not found'; end if;
  insert into public.voting_audit_log(event_id, actor_user_id, action) values (target_event_id, auth.uid(), 'event_closed');
end $$;
grant execute on function public.close_voting_event(bigint) to authenticated;

create or replace function public.submit_voting_ballot(target_event_id bigint, answers jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_account public.manager_portal_accounts%rowtype;
  v_event public.voting_events%rowtype;
  v_ballot_id bigint;
  answer_count integer;
  valid_count integer;
  required_count integer;
  required_answered integer;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if jsonb_typeof(answers) <> 'array' then raise exception 'Answers must be a JSON array'; end if;

  select * into v_account from public.manager_portal_accounts where auth_user_id = auth.uid() and active = true limit 1;
  if not found then raise exception 'Active manager account required'; end if;
  select * into v_event from public.voting_events where id = target_event_id for update;
  if not found then raise exception 'Voting event not found'; end if;
  if v_event.status <> 'open' then raise exception 'Voting event is not open'; end if;
  if v_event.opens_at is not null and now() < v_event.opens_at then raise exception 'Voting has not opened yet'; end if;
  if v_event.closes_at is not null and now() >= v_event.closes_at then raise exception 'Voting has closed'; end if;
  if not exists (select 1 from public.voting_electorate where event_id = target_event_id and manager_id = v_account.manager_id)
    then raise exception 'Manager is not in this vote''s electorate'; end if;

  with submitted as (
    select distinct (x->>'question_id')::bigint question_id, (x->>'option_id')::bigint option_id
    from jsonb_array_elements(answers) x
  ) select count(*) into answer_count from submitted;
  with submitted as (
    select distinct (x->>'question_id')::bigint question_id, (x->>'option_id')::bigint option_id
    from jsonb_array_elements(answers) x
  ) select count(*) into valid_count from submitted s
    join public.voting_questions q on q.id = s.question_id and q.event_id = target_event_id
    join public.voting_options o on o.id = s.option_id and o.question_id = q.id;
  if answer_count <> valid_count then raise exception 'One or more answers are invalid'; end if;

  select count(*) into required_count from public.voting_questions where event_id = target_event_id and required = true;
  with submitted as (
    select distinct (x->>'question_id')::bigint question_id from jsonb_array_elements(answers) x
  ) select count(*) into required_answered from public.voting_questions q join submitted s on s.question_id = q.id
    where q.event_id = target_event_id and q.required = true;
  if required_answered <> required_count then raise exception 'Please answer every required question'; end if;

  insert into public.voting_ballots(event_id, manager_id, submitted_by, submitted_at, updated_at)
  values (target_event_id, v_account.manager_id, auth.uid(), now(), now())
  on conflict (event_id, manager_id) do update set submitted_by = excluded.submitted_by, updated_at = now()
  returning id into v_ballot_id;

  delete from public.voting_responses where voting_responses.ballot_id = v_ballot_id;
  insert into public.voting_responses(ballot_id, question_id, option_id)
  select v_ballot_id, (x->>'question_id')::bigint, (x->>'option_id')::bigint from jsonb_array_elements(answers) x;
  insert into public.voting_audit_log(event_id, ballot_id, actor_user_id, manager_id, action, details)
  values (target_event_id, v_ballot_id, auth.uid(), v_account.manager_id, 'ballot_submitted', jsonb_build_object('answer_count', answer_count));
  return v_ballot_id;
end $$;
grant execute on function public.submit_voting_ballot(bigint, jsonb) to authenticated;

create or replace function public.get_voting_results(target_event_id bigint)
returns table(question_id bigint, question_title text, option_id bigint, option_label text, votes bigint)
language plpgsql security definer set search_path = public as $$
declare v_event public.voting_events%rowtype;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  select * into v_event from public.voting_events where id = target_event_id;
  if not found then raise exception 'Voting event not found'; end if;
  if not public.is_admin() then
    if v_event.results_visibility = 'hidden' then raise exception 'Results are hidden'; end if;
    if v_event.results_visibility = 'after_close' and not (v_event.status = 'closed' or (v_event.closes_at is not null and now() >= v_event.closes_at))
      then raise exception 'Results are not available until voting closes'; end if;
  end if;
  return query
  select q.id, q.title, o.id, o.label, count(r.ballot_id)::bigint
  from public.voting_questions q join public.voting_options o on o.question_id = q.id
  left join public.voting_responses r on r.question_id = q.id and r.option_id = o.id
  where q.event_id = target_event_id
  group by q.id, q.title, q.sort_order, o.id, o.label, o.sort_order
  order by q.sort_order, q.id, o.sort_order, o.id;
end $$;
grant execute on function public.get_voting_results(bigint) to authenticated;

